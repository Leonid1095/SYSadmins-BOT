#!/bin/bash
# Один проход сторожа: собрать факты → найти дельту → разобрать → уведомить,
# и отдельно — дожать то, что уже висит без ответа.
#
# Конвейер выстроен так, что дорогая часть включается последней: без дельты
# analyst.py возвращает "analysed: false", и ни модель, ни Telegram не трогаются.
#
# Дожим стоит ЗА конвейером и запускается всегда, даже когда дельты нет. В этом
# и смысл: напоминать надо ровно в те тихие проходы, когда ничего не менялось,
# а крит так и висит непрочитанным. Он же не должен падать вместе с доставкой,
# поэтому код возврата конвейера запоминается, а не обрывает проход.
#
# Работает под plg: credentials подписки принадлежат ему, а телеметрию, которой
# нужен root, сборщик берёт узкими правилами sudoers.
set -euo pipefail

cd "$(dirname "$(readlink -f "$0")")/.."
PY="./venv/bin/python"

status=0
"$PY" watchdog/collect.py \
  | "$PY" watchdog/delta.py \
  | "$PY" watchdog/analyst.py \
  | "$PY" watchdog/notify.py || status=$?

"$PY" watchdog/followup.py || status=$?

exit "$status"
